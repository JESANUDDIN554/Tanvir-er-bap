"""Build a signed Itraji Cliper update pack (see UPDATE_PACKS.md).

Usage:
  python3 tools/build_update_pack.py \
      --tree <dir with the FULL new loose set: ui/, fonts/, \
              corepack.enc> \
      --files ui/app.js,ui/index.html \
      --version 2.1 --out update-2.1.zip [--priv PATH]

--files lists the loose files that CHANGED (app-relative). The
tool always adds a freshly generated, freshly signed integrity.py
covering the full --tree set, so the applied result passes the
app's integrity check. Only loose files may be listed: ui/*,
fonts/*, corepack.enc. Compiled modules (.py) live inside the exe
and can never be updated this way - the tool refuses them.
"""
import argparse
import hashlib
import json
import os
import sys
import zipfile

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(HERE)
sys.path.insert(0, HERE)
sys.path.insert(0, ROOT)

import build_integrity  # noqa: E402
import ed25519  # noqa: E402


def _integrity_py_bytes(manifest, sig_hex):
    text = ('"""Signed integrity manifest - generated by '
            'tools/build_integrity.py. Do not edit."""\n\n')
    text += "MANIFEST = " + repr(manifest) + "\n\n"
    text += "SIGNATURE_HEX = " + repr(sig_hex) + "\n"
    return text.encode("utf-8")


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--tree", required=True,
                    help="folder holding the FULL new loose set")
    ap.add_argument("--files", required=True,
                    help="comma-separated changed loose files, "
                         "app-relative (ui/..., fonts/..., "
                         "corepack.enc)")
    ap.add_argument("--version", required=True)
    ap.add_argument("--out", required=True)
    ap.add_argument("--priv", default=os.path.join(
        HERE, "license_private_key.txt"))
    a = ap.parse_args()

    changed = [p.strip() for p in a.files.split(",") if p.strip()]
    for rel in changed:
        if rel == "integrity.py":
            print("do not list integrity.py - it is generated")
            return 1
        if not (rel == "corepack.enc" or rel.startswith("ui/")
                or rel.startswith("fonts/")):
            print(f"'{rel}' is not a loose file - compiled code "
                  "ships via the Setup, not update packs")
            return 1
        if not os.path.isfile(os.path.join(a.tree, *rel.split("/"))):
            print(f"'{rel}' not found under --tree {a.tree}")
            return 1

    with open(a.priv) as f:
        seed = bytes.fromhex(f.read().strip())

    # Full-set manifest over the tree, signed - becomes the pack's
    # integrity.py entry (same format build_integrity.py emits).
    manifest = build_integrity.collect(a.tree)
    blob = json.dumps(manifest, sort_keys=True).encode("utf-8")
    sig_hex = ed25519.sign(seed, blob).hex()
    integ = _integrity_py_bytes(manifest, sig_hex)

    entries = {}
    for rel in changed:
        with open(os.path.join(a.tree, *rel.split("/")), "rb") as f:
            entries[rel] = f.read()
    entries["integrity.py"] = integ

    files_meta = [{"path": rel,
                   "sha256": hashlib.sha256(data).hexdigest(),
                   "size": len(data)}
                  for rel, data in sorted(entries.items())]
    doc = {"version": a.version, "files": files_meta}
    pack_sig = ed25519.sign(
        seed, json.dumps(doc, sort_keys=True).encode("utf-8")).hex()

    with zipfile.ZipFile(a.out, "w", zipfile.ZIP_DEFLATED) as zf:
        zf.writestr("update.json",
                    json.dumps(doc, indent=2, sort_keys=True))
        zf.writestr("update.sig", pack_sig)
        for rel, data in entries.items():
            zf.writestr(rel, data)
    print(f"update pack written: {a.out} "
          f"(version {a.version}, {len(entries)} files incl. "
          f"integrity.py, manifest covers {len(manifest)} files)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
